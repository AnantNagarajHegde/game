"""Generate CurriculumData.g.cs for Unity from curriculum/flow.json and the learning-design JSON.

Run from game/village_backend after any change to flow.json, npc.json or the curriculum JSON:
    python tools/gen_curriculum_cs.py
test_curriculum.py fails if the generated file is out of date.
"""
import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))
import curriculum_engine as ce  # noqa: E402

TARGET = BACKEND.parent / "My project (1)" / "Assets" / "_Paridhwani" / "Scripts" / "Runtime" / "CurriculumData.g.cs"
ROLES = {"TeaVendor", "Librarian", "MessOwner"}


def s(value):
    return json.dumps(value or "", ensure_ascii=False)


def line(value):
    if not value:
        return "null"
    return f"new CurriculumLine({s(value.get('kn'))},{s(value.get('ro'))},{s(value.get('en'))})"


def strings(values):
    return "new string[]{" + ",".join(s(v) for v in values) + "}"


def generate(engine=None):
    e = engine or ce.CurriculumEngine(live=False)
    out = ["// <auto-generated> by village_backend/tools/gen_curriculum_cs.py from curriculum/flow.json",
           "// and language-engine/learning-design/content. Do not edit by hand. </auto-generated>",
           "namespace Paridhwani", "{", "    public static partial class CurriculumData", "    {",
           "        public static readonly CurriculumNode[] Nodes = {"]
    for node in e.flow["nodes"]:
        main = e.line_for(node)
        task, hint, example = "", "", None
        if node.get("quest"):
            quest, step = e.steps[node["step"]]
            hint = quest.get("quick_hint", "")
            full = step.get("full_example")
            if full:
                example = {"kn": full["kannada"], "ro": full["kanglish"], "en": full["english"]}
            if node["kind"] == "respond":
                task = step.get("task", "")
                if node.get("english_hidden") and not task:
                    task = "Work out the meaning."
        choices = []
        for choice in node["choices"]:
            text = e.choice_text(node, choice)
            reaction = None
            if choice.get("wrong"):
                if node["kind"] == "respond":
                    result = e.turn({"version": 1, "node": node["id"], "text": text["ro"] or text["kn"],
                                     "player_name": "Arun", "wrong_count": 0})
                    r = result["reaction"]
                    reaction = {"kn": r["kn"], "ro": r["ro"], "en": r["en"] or ("(" + r["action"] + ")" if r["action"] else "")}
                else:
                    reaction = {"kn": "", "ro": "", "en": "Not that one. Look again."}
            choices.append("                new CurriculumChoice({},{},{},{},{},{},{})".format(
                s(choice["key"]), line(text), s(choice["next"]), strings(choice.get("effects", [])),
                strings(choice.get("completes", [])), "true" if choice.get("wrong") else "false", line(reaction)))
        out.append("            new CurriculumNode({},{},{},{},{},{},{},{},{},{},{},{}, new CurriculumChoice[]{{".format(
            s(node["id"]), s(node["npc"]), s(node["kind"]), s(node.get("quest")), s(node.get("step")), line(main),
            s(task), s(hint), line(example), "true" if node.get("silent") else "false",
            "true" if node.get("optional") else "false", "true" if node.get("english_hidden") else "false"))
        out.append(",\n".join(choices))
        out.append("            }),")
    out.append("        };")
    out.append("        public static readonly CurriculumQuest[] Quests = {")
    removed = set(e.flow["removed_quests"])
    for quest_id, quest in sorted(e.quests.items()):
        if quest_id in removed:
            continue
        out.append("            new CurriculumQuest({},{},{},{}),".format(
            s(quest_id), quest["level"], s(quest["title"]), s(quest.get("objective", ""))))
    out.append("        };")
    out.append("        public static readonly CurriculumLevel[] Levels = {")
    progression = json.loads((e.root / "learning-design" / "content" / "progression.json").read_text(encoding="utf-8-sig"))
    for level in progression["levels"]:
        quests = [q for q in level["quests"] if q not in removed]
        out.append("            new CurriculumLevel({},{},{},{}),".format(
            level["level"], s(level["name"]), strings(quests), s(e.flow["levels"][str(level["level"])]["next"])))
    out.append("        };")
    out.append("        public static readonly CurriculumNpcInfo[] Npcs = {")
    for key, npc in e.flow["npcs"].items():
        assert npc["role"] in ROLES, npc["role"]
        out.append("            new CurriculumNpcInfo({},VillageNpcRole.{},{},{},{}),".format(
            s(key), npc["role"], s(npc["display"]), s(npc["start"]), npc["level"]))
    out.append("        };")
    out += ["    }", "}", ""]
    return "\n".join(out)


if __name__ == "__main__":
    text = generate()
    check = "--check" in sys.argv
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if check:
        print("up to date" if current == text else "OUT OF DATE")
        sys.exit(0 if current == text else 1)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
